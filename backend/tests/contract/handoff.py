"""Generate Person-3 contract handoff artifacts for C1 (risk 5).

    python -m tests.contract.handoff        (from backend/, venv active)

Writes ``docs/handoff/p3_openapi.json`` (OpenAPI of the running app) and
``docs/handoff/P3_ENDPOINT_INVENTORY.md`` (implemented routes vs the docs/API_CONTRACTS.md
catalogue). ``tests/contract/test_handoff_up_to_date.py`` fails when they are stale.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import app  # noqa: F401  (SQLAlchemy runtime flag)
from app.main import create_app

REPO = Path(__file__).resolve().parents[3]
CONTRACT_DOC = REPO / "docs" / "API_CONTRACTS.md"
OUT_DIR = REPO / "docs" / "handoff"
OPENAPI_FILE = OUT_DIR / "p3_openapi.json"
INVENTORY_FILE = OUT_DIR / "P3_ENDPOINT_INVENTORY.md"
PREFIX = "/api/v1"
# Contract prefixes that belong to Person 3 (AGENT_TEAM / P3_PLANNER_LEARNING_GUIDELINES §6).
P3_PREFIXES = (
    "/profile", "/events", "/assessments", "/tasks", "/planner", "/plans", "/sessions", "/decks", "/cards",
    "/reviews", "/quizzes", "/attempts", "/mastery", "/study-needs", "/notes", "/annotations", "/errors",
    "/focus", "/analytics", "/notifications", "/grades", "/account",
)
OWNED_BY_OTHERS = {"/grades/import": "C1", "/tasks/decompose (AI variant)": "G", "/annotations": "C1/G (needs documents)"}


def _norm(path: str) -> str:
    return re.sub(r"\{[^}]+\}", "{}", path.rstrip("/"))


def contract_endpoints() -> set[tuple[str, str]]:
    out: set[tuple[str, str]] = set()
    for line in CONTRACT_DOC.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        first = line.split("|")[1]
        for part in first.split(";"):
            m = re.match(r"\s*([A-Z/]+)\s+(/[^\s|]+)", part)
            if not m:
                continue
            methods, path = m.group(1), m.group(2)
            for method in methods.split("/"):
                if method in {"GET", "POST", "PUT", "PATCH", "DELETE"}:
                    out.add((method, _norm(path)))
    return out


def app_endpoints(spec: dict) -> set[tuple[str, str]]:
    out = set()
    for path, ops in spec["paths"].items():
        if path.startswith(PREFIX):
            for method in ops:
                out.add((method.upper(), _norm(path[len(PREFIX):])))
    return out


def build() -> tuple[str, str]:
    application = create_app("sqlite://")
    openapi = application.openapi()
    spec = json.dumps(openapi, indent=2, ensure_ascii=False, sort_keys=True) + "\n"
    implemented = app_endpoints(openapi)
    contract = contract_endpoints()
    p3_contract = {e for e in contract if e[1].startswith(P3_PREFIXES)}
    in_both = sorted(implemented & p3_contract, key=lambda e: (e[1], e[0]))
    extra = sorted(implemented - contract, key=lambda e: (e[1], e[0]))
    missing = sorted(p3_contract - implemented, key=lambda e: (e[1], e[0]))

    def rows(items):
        return "\n".join(f"| `{m}` | `{p}` |" for m, p in items) or "| — | — |"

    md = f"""# Person 3 — endpoint inventory (generated)

Generated by `python -m tests.contract.handoff` from the running app and `docs/API_CONTRACTS.md`.
Do not edit by hand; `tests/contract/test_handoff_up_to_date.py` checks it. Paths relative to `{PREFIX}`,
path parameters normalized to `{{}}`. Full schemas: [`p3_openapi.json`](p3_openapi.json).

## In the contract and implemented ({len(in_both)})
| Method | Path |
|---|---|
{rows(in_both)}

## Implemented but NOT in the contract — needs C1 review ({len(extra)})
| Method | Path |
|---|---|
{rows(extra)}

## In the Person-3 part of the contract but not implemented ({len(missing)})
| Method | Path |
|---|---|
{rows(missing)}
"""
    return spec, md


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    spec, md = build()
    OPENAPI_FILE.write_text(spec, encoding="utf-8")
    INVENTORY_FILE.write_text(md, encoding="utf-8")
    print(f"wrote {OPENAPI_FILE.relative_to(REPO)} and {INVENTORY_FILE.relative_to(REPO)}")


if __name__ == "__main__":
    main()
